WORK="$(mktemp -d "${TMPDIR:-/tmp}/pln-repackage.XXXXXX")"

cleanup() {
  rm -rf "$WORK"
}
trap cleanup EXIT INT TERM

die() {
  echo "[error] $*" >&2
  exit 1
}

progress() {
  printf '\033[1;36m[%3s%%]\033[0m %s\n' "$1" "$2"
}

