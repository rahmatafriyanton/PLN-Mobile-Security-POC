[[ "$actual_sha" == "$EXPECTED_APK_SHA256" ]] || die \
  "APK sumber berbeda. expected=$EXPECTED_APK_SHA256 actual=$actual_sha"

DECODED="$WORK/decoded"
STAGE="$WORK/stage"
mkdir -p "$STAGE" "$(dirname "$OUTPUT_APK")"

progress 10 "Preparing injection..."
